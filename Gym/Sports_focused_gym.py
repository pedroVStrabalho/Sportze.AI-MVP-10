def get_sports() -> list[str]:
    """Return all sports available in the catalog."""
    return list(CATALOG.keys())


def get_all_sessions() -> list[dict[str, Any]]:
    """Return a flat copy of every session in the catalog."""
    return deepcopy([session for sessions in CATALOG.values() for session in sessions])


def get_sessions(sport: str) -> list[dict[str, Any]]:
    """Return all sessions for one sport. Case-insensitive; underscores are allowed."""
    key = _resolve_sport_key(sport)
    return deepcopy(CATALOG[key])


def get_session(sport: str, session_number: int) -> dict[str, Any]:
    """Return one session by sport and session number."""
    key = _resolve_sport_key(sport)
    for session in CATALOG[key]:
        if session["session_number"] == session_number:
            return deepcopy(session)
    raise KeyError(f"Session {session_number} not found for {key}")


def search_sessions(query: str) -> list[dict[str, Any]]:
    """Search across sport, session title, focus, exercise names, and prescriptions."""
    q = query.strip().lower()
    results: list[dict[str, Any]] = []
    for sport, sessions in CATALOG.items():
        for session in sessions:
            haystack = " ".join([
                sport,
                session["name"],
                session["focus"],
                " ".join(
                    f'{exercise["name"]} {exercise["prescription"]}'
                    for exercise in session["exercises"]
                ),
            ]).lower()
            if q in haystack:
                item = deepcopy(session)
                item["sport"] = sport
                results.append(item)
    return results


def _resolve_sport_key(sport: str) -> str:
    normalized = sport.strip().replace("_", " ").lower()
    for key in CATALOG:
        if key.lower() == normalized:
            return key
    raise KeyError(f"Sport not found: {sport}. Available sports: {', '.join(CATALOG)}")


